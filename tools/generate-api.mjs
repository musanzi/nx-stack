import { randomUUID } from 'node:crypto';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const input = process.env.OPENAPI_INPUT ?? 'http://localhost:8000/openapi.json';
const source = /^https?:\/\//i.test(input) ? new URL(input) : pathToFileURL(resolve(input));
const output = fileURLToPath(new URL('../libs/api-contracts/src/lib/schema.ts', import.meta.url));
const temporaryOutput = `${output}.${randomUUID()}.tmp`;

try {
  const ast = await openapiTS(source);
  const contents = `/** Generated by openapi-typescript. Do not edit manually. */\n${astToString(ast)}`;
  await mkdir(dirname(output), { recursive: true });
  await writeFile(temporaryOutput, contents);
  await rename(temporaryOutput, output);
  console.log(`API contracts generated from ${input}`);
} finally {
  await rm(temporaryOutput, { force: true });
}
