import { randomUUID } from 'node:crypto';
import { mkdir, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import ts from 'typescript';

const input =
  process.env.OPENAPI_INPUT ?? fileURLToPath(new URL('../libs/api-contracts/openapi.json', import.meta.url));
const source = /^https?:\/\//i.test(input) ? new URL(input) : pathToFileURL(resolve(input));
const root = new URL('../libs/api-contracts/src/', import.meta.url);
const temporarySuffix = `.${randomUUID()}.tmp`;
const outputs = [];

try {
  const ast = await openapiTS(source);
  const components = ast.find((node) => ts.isInterfaceDeclaration(node) && node.name.text === 'components');
  const schemas = components?.members.find((member) => member.name?.text === 'schemas')?.type;
  const aliases = (schemas && ts.isTypeLiteralNode(schemas) ? schemas.members : [])
    .map((member) => member.name.text)
    .sort()
    .map((name) => `export type I${name} = components['schemas']['${name}'];`);

  const files = [
    ['lib/schema.ts', `/** Generated by openapi-typescript. Do not edit manually. */\n${astToString(ast)}`],
    [
      'index.ts',
      [
        '// Generated by tools/generate-api.mjs. Do not edit manually.',
        "import type { components } from './lib/schema';",
        "export type { components, operations, paths } from './lib/schema';",
        ...aliases,
        ''
      ].join('\n')
    ]
  ];

  // Prepare both generated files before replacing the committed contracts.
  for (const [name, contents] of files) {
    const output = fileURLToPath(new URL(name, root));
    const temporaryOutput = `${output}${temporarySuffix}`;
    outputs.push({ output, temporaryOutput });
    await mkdir(dirname(output), { recursive: true });
    await writeFile(temporaryOutput, contents);
  }
  for (const { output, temporaryOutput } of outputs) {
    await rename(temporaryOutput, output);
  }
  console.log(`API contracts generated from ${input}`);
} finally {
  for (const { temporaryOutput } of outputs) {
    await rm(temporaryOutput, { force: true });
  }
}
